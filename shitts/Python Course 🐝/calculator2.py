num1 = float(input("Enter Your First Number : "))
op = input("Choose your Operator : ")
num2 = float(input("Now Enter your Second Number : "))


if op == "+":
    print(num1 + num2)
elif op == "-":
    print(num1 - num2)
elif op == "/":
    print(num1 / num2)
elif op == "//":
    print(num1 // num2)
elif op == "*":
    print(num1 * num2)
elif op == "**":
    print(num1 ** num2)
else:
    print("Invalid Operator")




























